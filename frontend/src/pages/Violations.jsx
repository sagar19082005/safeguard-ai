import { useEffect, useState } from "react";
import { api } from "../api";

export default function Violations() {
  const [items, setItems] = useState([]);
  const [error, setError] = useState("");
  const load = () => api("/violations").then(setItems).catch((err) => setError(err.message));
  useEffect(() => { load(); }, []);
  const update = async (id, review_status) => {
    try { await api(`/violations/${id}`, { method: "PATCH", body: { review_status } }); load(); }
    catch (err) { setError(err.message); }
  };
  return <div className="space-y-6">
    <div><h1 className="text-xl font-semibold">Violations</h1><p className="mt-1 text-sm text-muted">Review PPE violations generated by configured workplace rules.</p></div>
    {error && <p role="alert" className="rounded border border-bad/40 bg-bad/10 p-3 text-sm text-bad">{error}</p>}
    <section className="overflow-x-auto rounded border border-line bg-surface">
      <table className="w-full text-left text-sm"><thead className="border-b border-line text-xs text-muted"><tr><th className="p-4">Time</th><th className="p-4">Location</th><th className="p-4">Missing PPE</th><th className="p-4">Severity</th><th className="p-4">Status</th></tr></thead>
        <tbody>{items.map((item) => <tr key={item.id} className="border-b border-line last:border-0"><td className="whitespace-nowrap p-4 text-xs text-muted">{item.created_at ? new Date(item.created_at).toLocaleString() : "-"}</td><td className="p-4">{item.location_name || item.camera_name}</td><td className="p-4 font-medium">{item.missing_item}</td><td className="p-4 capitalize">{item.severity}</td><td className="p-4"><select className="field py-1 text-xs" value={item.review_status} onChange={(e) => update(item.id, e.target.value)}><option value="new">New</option><option value="acknowledged">Acknowledged</option><option value="under_review">Under review</option><option value="resolved">Resolved</option><option value="false_positive">False positive</option></select></td></tr>)}</tbody>
      </table>
      {!items.length && <p className="p-5 text-sm text-muted">No violations recorded.</p>}
    </section>
  </div>;
}
